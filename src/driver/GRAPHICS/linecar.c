void display_draw_linecar (uint16_t x,
                           uint16_t y,
                           uint16_t linecar_color,
                           uint16_t bg_color)
{ 
    RA8875_graphic_mode();
    RA8875_fill_screen(bg_color);

    for (uint16_t row = 0; row < LINECAR_HEIGHT; row++)
    {
        for (uint16_t col = 0; col < LINECAR_WIDTH; col++)
        {
            uint16_t byte_index = (row * LINECAR_BYTES_PER_ROW) + (col / 8);
            uint8_t bit_mask = 0x80 >> (col % 8);

            if ((linecar_bitmap[byte_index] & bit_mask) == 0)
            {
                RA8875_draw_pixel(x + col, y + row, linecar_color);
            }
        }
    }
}

